export function normalizeLocaleCode(locale) {
  const raw = String(locale || 'en').trim().toLowerCase()
  if (raw.startsWith('zh')) return 'zh'
  if (raw.startsWith('ru')) return 'ru'
  return 'en'
}

export function resolveLocaleDictionary(locale) {
  const code = normalizeLocaleCode(locale)
  return code === 'zh' ? zh : en
}

export function createTranslator(ctx, props, baseDict = en) {
  const slotT = typeof props?.t === 'function' ? props.t : null
  const bindT = typeof ctx?.locale?.bind === 'function' ? ctx.locale.bind(NS) : null
  return new Proxy(baseDict, {
    get(target, prop) {
      if (typeof prop !== 'string') return target[prop]
      if (slotT) {
        try {
          const res = slotT(prop)
          if (res && res !== prop && res !== `${NS}.${prop}`) return res
        } catch (_err) {
          // fallback
        }
      }
      if (bindT) {
        try {
          const res = bindT(prop)
          if (res && res !== prop && res !== `${NS}.${prop}`) return res
        } catch (_err) {
          // fallback
        }
      }
      if (typeof ctx?.locale?.t === 'function') {
        try {
          const res = ctx.locale.t(`${NS}.${prop}`) || ctx.locale.t(prop)
          if (res && res !== prop && res !== `${NS}.${prop}`) return res
        } catch (_err) {
          // fallback
        }
      }
      return target[prop] ?? prop
    },
  })
}

export function registerClientLocales(ctx, namespace = NS) {
  return ctx.effect(
    () => ctx.locale.register(namespace, { en, zh }),
    'dsh-model-sync: dictionaries'
  )
}
